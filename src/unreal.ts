import type { CrddIr } from "./model.ts";

export type GeneratedFile = {
  name: string;
  content: string;
};

export function generateUnreal(ir: CrddIr): GeneratedFile[] {
  const operation = ir.operation;
  const traceComment = operation.traces.map((id) => `// CRDD-TRACE: ${id}`).join("\n");
  const errorValues = operation.errors.map((error) => `\t${error.code},`).join("\n");
  const checks = operation.requires
    .map(
      (requirement) =>
        `\t// ${requirement.id}: ${requirement.expression}\n` +
        `\t// Generated adapter must evaluate this contract and return EPlaceWallError::${requirement.error}.`,
    )
    .join("\n\n");

  const header = `// Generated by crdd-ir. Do not edit this file directly.
${traceComment}
#pragma once

#include "CoreMinimal.h"
#include "PlaceWall.generated.h"

UENUM(BlueprintType)
enum class EPlaceWallError : uint8
{
\tNone,
${errorValues}
};

USTRUCT(BlueprintType)
struct FPlaceWallInput
{
\tGENERATED_BODY()

\tUPROPERTY(EditAnywhere, BlueprintReadWrite)
\tdouble LengthMeters = 0.0;

\tUPROPERTY(EditAnywhere, BlueprintReadWrite)
\tint64 CostJPY = 0;
};

struct FPlaceWallResult
{
\tbool bSucceeded = false;
\tEPlaceWallError Error = EPlaceWallError::None;
};

class FPlaceWallOperation
{
public:
\t// Extension point: connect domain state through an Unreal-specific adapter.
\tstatic FPlaceWallResult Execute(const FPlaceWallInput& Input);
};
`;

  const source = `// Generated by crdd-ir. Do not edit this file directly.
${traceComment}
#include "PlaceWall.h"

FPlaceWallResult FPlaceWallOperation::Execute(const FPlaceWallInput& Input)
{
${checks}

\t// CRDD-EXTENSION-POINT: Apply all effects atomically through the domain transaction adapter.
\t// Effects:
${operation.effects.map((effect) => `\t// - ${effect.action} ${effect.target}`).join("\n")}
\treturn { true, EPlaceWallError::None };
}
`;

  const test = `// Generated by crdd-ir. Complete adapter bindings in the human-owned test fixture.
${traceComment}
#include "Misc/AutomationTest.h"
#include "PlaceWall.h"

IMPLEMENT_SIMPLE_AUTOMATION_TEST(
\tFPlaceWallBoundaryTest,
\t"CRDD.PlaceWall.MinimumLengthBoundary",
\tEAutomationTestFlags::EditorContext | EAutomationTestFlags::EngineFilter)

bool FPlaceWallBoundaryTest::RunTest(const FString& Parameters)
{
\tFPlaceWallInput BelowBoundary;
\tBelowBoundary.LengthMeters = 0.299;

\tFPlaceWallInput AtBoundary;
\tAtBoundary.LengthMeters = 0.300;

\t// CRDD-EXTENSION-POINT: provide budget state and execute through the domain adapter.
\tAddInfo(TEXT("0.299m must fail; 0.300m must succeed."));
\treturn true;
}
`;

  return [
    { name: "PlaceWall.generated.h", content: header },
    { name: "PlaceWall.generated.cpp", content: source },
    { name: "PlaceWall.generated.spec.cpp", content: test },
  ];
}
